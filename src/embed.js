const { EmbedBuilder } = require("discord.js");
const {
  LEETCODE_FAVICON_URL,
  LEETCODE_BASE_URL,
  BOT_NAME,
} = require("./constants");

/** @typedef {import('./api').LeetCodeUser} LeetCodeUser */
/** @typedef {import('./api').SolvedCount} SolvedCount */
/** @typedef {import('./api').LeetCodeProblem} LeetCodeProblem */

module.exports = {
  /**
   * embeds a leetcode problem into a discord embed
   * @param {LeetCodeProblem} problem - the leetcode problem object
   * @param {string} title - the embed title
   * @returns {EmbedBuilder} the discord embed
   */
  embedProblem(problem, title) {
    const difficultyIcon = buildDifficultyIcon(problem.difficulty);
    const tags = buildTagsString(problem.tags);
    const reactions = buildReactionsString(problem.likes, problem.dislikes);

    return new EmbedBuilder()
      .setAuthor({ name: title, iconURL: LEETCODE_FAVICON_URL })
      .setURL(problem.url)
      .setTitle(`${problem.id}. ${problem.title}`)
      .setColor(0xffd700)
      .setDescription(`${difficultyIcon}  ${problem.difficulty}`)
      .addFields({ name: "Tags", value: tags })
      .addFields({ name: "Reactions", value: reactions })
      .setFooter({ text: `generated by ${BOT_NAME}` })
      .setTimestamp();
  },

  /**
   * embeds a leetcode user into a discord embed
   * @param {LeetCodeUser} user - the leetcode user object
   * @returns {EmbedBuilder} the discord embed
   */
  embedUser(user) {
    const skillTags = buildTagsString(user.skill_tags);
    const solvedTags = buildSolvedTags(user.solved);
    const activity = buildActivity(user.streak, user.total_active_days);
    const socials = buildSocials(
      user.githubUrl,
      user.linkedinUrl,
      user.twitterUrl
    );

    const embed = new EmbedBuilder()
      .setAuthor({ name: "User profile", iconURL: LEETCODE_FAVICON_URL })
      .setURL(`${LEETCODE_BASE_URL}/u/${user.username}/`)
      .setTitle(`${user.real_name} on LeetCode`)
      .setThumbnail(user.avatar)
      .setDescription(`${user.about}\n\n ${socials}`)
      .addFields(
        { name: `Past Year Activity`, value: activity },
        { name: "Solved Problems", value: solvedTags },
        { name: "Skill Tags", value: skillTags },
        { name: "Ranking", value: `#\`${user.ranking}\`` }
      )
      .setFooter({ text: `generated by ${BOT_NAME}` })
      .setTimestamp();

    if (user.about) {
      embed.setDescription(user.about);
    }

    return embed;
  },
};

/**
 * builds the difficulty icon based on the difficulty
 * @param {string} difficulty - the problem difficulty
 * @returns {string} the difficulty icon
 */
function buildDifficultyIcon(difficulty) {
  difficulty = difficulty.toLowerCase();

  if (difficulty === "easy") {
    return ":green_square:";
  } else if (difficulty === "medium") {
    return ":orange_square:";
  } else {
    return ":red_square:";
  }
}

/**
 * builds a string of tags formatted for discord embed
 * @param {string[]} tags - array of tags
 * @returns {string} the formatted tags string
 */
function buildTagsString(tags) {
  let tagsString = "";

  for (const tag of tags) {
    tagsString += `\`${tag}\` `;
  }

  return tagsString;
}

/**
 * builds a string of likes and dislikes formatted for discord embed
 * @param {number} likes - number of likes
 * @param {number} dislikes - number of dislikes
 * @returns {string} the formatted reactions string
 */
function buildReactionsString(likes, dislikes) {
  return `:thumbsup: \`${likes}\`  :thumbsdown: \`${dislikes}\``;
}

/**
 * builds a string of count of solved problems by difficulty formatted for discord embed
 * @param {SolvedCount[]} solved - array of count of solved problems by difficulty
 * @returns {string} the formatted count of solved problems string
 */
function buildSolvedTags(solved) {
  let res = "";

  for (const row of solved) {
    const icon = buildDifficultyIcon(row.difficulty);
    res += `${icon}  ${row.difficulty}: \`${row.count}\`   `;
  }

  return res;
}

/**
 * builds activity string for user embed
 * @param {number} streak - user's max streak
 * @param {number} total_active_days - user's total active days
 * @returns {string} the formatted activity string
 */
function buildActivity(streak, total_active_days) {
  let res = "";

  res += `Max Streak: \`${streak}\` day` + (streak !== 1 ? "s" : "") + "\n";
  res +=
    `Active: \`${total_active_days}\` day` +
    (total_active_days !== 1 ? "s" : "");

  return res;
}

/**
 * builds social links string for user embed
 * @param {string?} githubUrl - user's github url
 * @param {string?} linkedinUrl - user's linkedin url
 * @param {string?} twitterUrl - user's twitter url
 * @returns {string} the formatted social links string
 */
function buildSocials(githubUrl, linkedinUrl, twitterUrl) {
  let res = "";

  if (githubUrl) {
    res += `🐙 [GitHub](${githubUrl})`;
  }

  if (linkedinUrl || twitterUrl) {
    res += " • ";
  }

  if (linkedinUrl) {
    res += ` 💼 [LinkedIn](${linkedinUrl})`;
  }

  if (linkedinUrl && twitterUrl) {
    res += " • ";
  }

  if (twitterUrl) {
    res += ` 𝕏 [Twitter](${twitterUrl})`;
  }

  // zero-width space to prevent trimming of trailing spaces
  res += "\n";
  res += "\u200B";

  return res;
}
